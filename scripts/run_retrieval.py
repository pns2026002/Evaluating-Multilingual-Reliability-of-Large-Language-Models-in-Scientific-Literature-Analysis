#!/usr/bin/env python3
"""Run BM25 and dense retrieval baselines on BEIR SciFact.

No translations are generated by this script. For Hindi evaluation, provide an ID-aligned
CSV with human-reviewed Hindi translations.
"""
import argparse, json, os, random, sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
from beir import util
from beir.datasets.data_loader import GenericDataLoader
from rank_bm25 import BM25Okapi
from sentence_transformers import SentenceTransformer
from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS

EN_MODEL = "sentence-transformers/all-MiniLM-L6-v2"
MULTI_MODEL = "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"


def tokenize(text):
    # A simple whitespace/lowercase tokenizer for a transparent BM25 baseline.
    # This is not language-aware; that limitation is relevant for Hindi queries.
    return [t.strip(".,;:!?()[]{}\"'`).") for t in str(text).lower().split() if t.strip(".,;:!?()[]{}\"'`).")]


def recall_at_k(ranked_ids, relevant_ids, k):
    if not relevant_ids:
        return np.nan
    return len(set(ranked_ids[:k]) & relevant_ids) / len(relevant_ids)


def reciprocal_rank_at_k(ranked_ids, relevant_ids, k):
    for i, doc_id in enumerate(ranked_ids[:k], start=1):
        if doc_id in relevant_ids:
            return 1.0 / i
    return 0.0


def load_hindi(path, queries):
    if not path or not Path(path).exists():
        raise FileNotFoundError("Hindi run requested, but --hindi_csv was not supplied or does not exist. Copy data/hindi_queries_template.csv to data/hindi_queries.csv, add reviewed translations, and rerun.")
    df = pd.read_csv(path, dtype={"query_id": str})
    required = {"query_id", "english_text", "hindi_text", "translation_method", "human_checked"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Hindi CSV is missing required columns: {sorted(missing)}")
    df["query_id"] = df["query_id"].astype(str)
    known = set(map(str, queries.keys()))
    unknown = set(df.query_id) - known
    if unknown:
        raise ValueError(f"Hindi CSV has unknown query IDs (sample): {sorted(unknown)[:5]}")
    if df.query_id.duplicated().any():
        raise ValueError("Hindi CSV contains duplicate query_id values.")
    if df.hindi_text.isna().any() or (df.hindi_text.astype(str).str.strip() == "").any():
        raise ValueError("Hindi CSV has empty hindi_text values.")
    # Warn, but do not block, if not all translations have been human checked.
    unchecked = (~df.human_checked.astype(str).str.lower().isin(["true", "1", "yes", "y"])).sum()
    if unchecked:
        print(f"WARNING: {unchecked} Hindi translations are not marked human_checked.", file=sys.stderr)
    return {str(r.query_id): str(r.hindi_text) for r in df.itertuples()}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--data_dir", default="data/beir")
    p.add_argument("--output_dir", default="results")
    p.add_argument("--languages", default="en", help="Comma-separated: en,hi")
    p.add_argument("--hindi_csv", default=None)
    p.add_argument("--limit_queries", type=int, default=0, help="Optional smoke test; 0 means all test queries")
    p.add_argument("--batch_size", type=int, default=64)
    args = p.parse_args()
    random.seed(42); np.random.seed(42)
    out_dir = Path(args.output_dir); out_dir.mkdir(parents=True, exist_ok=True)
    data_dir = Path(args.data_dir); data_dir.mkdir(parents=True, exist_ok=True)
    dataset_path = data_dir / "scifact"
    if not dataset_path.exists():
        url = "https://public.ukp.informatik.tu-darmstadt.de/thakur/BEIR/datasets/scifact.zip"
        util.download_and_unzip(url, str(data_dir))
    corpus, queries, qrels = GenericDataLoader(data_folder=str(dataset_path)).load(split="test")
    queries = {str(k): str(v) for k, v in queries.items()}
    qrels = {str(q): {str(d): int(rel) for d, rel in rels.items()} for q, rels in qrels.items()}
    if args.limit_queries > 0:
        keep = list(queries)[:args.limit_queries]
        queries = {k: queries[k] for k in keep}
        qrels = {k: qrels.get(k, {}) for k in keep}
    languages = [x.strip().lower() for x in args.languages.split(",") if x.strip()]
    if any(x not in {"en", "hi"} for x in languages):
        raise ValueError("Supported languages in this starter are en,hi")
    hindi = load_hindi(args.hindi_csv, queries) if "hi" in languages else {}

    doc_ids = list(corpus.keys())
    doc_texts = [(str(corpus[d].get("title", "")) + " " + str(corpus[d].get("text", ""))).strip() for d in doc_ids]
    tokenized_corpus = [tokenize(x) for x in doc_texts]
    bm25 = BM25Okapi(tokenized_corpus)
    dense_models = {
        "english_dense": SentenceTransformer(EN_MODEL),
        "multilingual_dense": SentenceTransformer(MULTI_MODEL),
    }
    doc_embeddings = {}
    for name, model in dense_models.items():
        cache_path = data_dir / f"corpus_emb_{name}.npy"
        if cache_path.exists():
            print(f"Loading cached corpus embeddings for {name} from {cache_path}")
            doc_embeddings[name] = np.load(cache_path)
        else:
            print(f"Computing corpus embeddings for {name}...")
            embs = model.encode(doc_texts, convert_to_numpy=True, normalize_embeddings=True, show_progress_bar=True, batch_size=args.batch_size)
            np.save(cache_path, embs)
            doc_embeddings[name] = embs

    query_rows, summary_rows = [], []
    for lang in languages:
        active_queries = queries if lang == "en" else {qid: hindi[qid] for qid in queries if qid in hindi}
        if not active_queries:
            raise ValueError(f"No queries available for language {lang}")
        for qid, qtext in active_queries.items():
            relevant = {d for d, rel in qrels.get(qid, {}).items() if rel > 0}
            if not relevant:
                continue
            bm_scores = bm25.get_scores(tokenize(qtext))
            bm_rank = np.argsort(-bm_scores)[:10]
            rankings = {"bm25": [doc_ids[i] for i in bm_rank]}
            for name, model in dense_models.items():
                qemb = model.encode([qtext], convert_to_numpy=True, normalize_embeddings=True, show_progress_bar=False)[0]
                scores = doc_embeddings[name] @ qemb
                idx = np.argsort(-scores)[:10]
                rankings[name] = [doc_ids[i] for i in idx]
            for method, ranked in rankings.items():
                row = {"query_id": qid, "language": lang, "method": method,
                       "num_relevant_docs": len(relevant), "first_relevant_rank": next((i for i,d in enumerate(ranked, 1) if d in relevant), None),
                       "reciprocal_rank_at_10": reciprocal_rank_at_k(ranked, relevant, 10),
                       "recall_at_1": recall_at_k(ranked, relevant, 1),
                       "recall_at_5": recall_at_k(ranked, relevant, 5),
                       "recall_at_10": recall_at_k(ranked, relevant, 10),
                       "top10_doc_ids": " ".join(ranked)}
                query_rows.append(row)
    qdf = pd.DataFrame(query_rows)
    qdf.to_csv(out_dir / "query_level_results.csv", index=False)
    for (lang, method), grp in qdf.groupby(["language", "method"]):
        summary_rows.append({"language": lang, "method": method, "n_queries": len(grp),
                             "MRR@10": grp.reciprocal_rank_at_10.mean(),
                             "Recall@1": grp.recall_at_1.mean(), "Recall@5": grp.recall_at_5.mean(),
                             "Recall@10": grp.recall_at_10.mean()})
    sdf = pd.DataFrame(summary_rows).sort_values(["language", "method"])
    sdf.to_csv(out_dir / "retrieval_metrics.csv", index=False)
    # Failure cases: relevant documents exist, but no relevant document appears in top 10.
    fails = qdf[qdf.reciprocal_rank_at_10 == 0].copy()
    fails.to_csv(out_dir / "failure_cases.csv", index=False)
    metadata = {"timestamp_utc": datetime.now(timezone.utc).isoformat(), "dataset": "BEIR SciFact", "split": "test",
                "n_corpus_docs": len(corpus), "n_queries_loaded": len(queries), "languages": languages,
                "methods": {"bm25": "rank-bm25; whitespace tokenizer", "english_dense": EN_MODEL, "multilingual_dense": MULTI_MODEL},
                "top_k": [1, 5, 10], "seed": 42, "hindi_csv": args.hindi_csv,
                "note": "Metrics are generated by this run. Hindi queries are user-supplied translations; translation provenance must be documented."}
    (out_dir / "run_metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print("\n=== RETRIEVAL METRICS (actual run output) ===")
    print(sdf.to_string(index=False))
    print(f"\nSaved: {out_dir / 'retrieval_metrics.csv'}; {out_dir / 'query_level_results.csv'}; {out_dir / 'failure_cases.csv'}; {out_dir / 'run_metadata.json'}")

if __name__ == "__main__":
    main()
